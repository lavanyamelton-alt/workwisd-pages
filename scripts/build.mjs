// Netlify build step: bakes style.css (minified) and site-config.json into a JS
// module the function imports, so nothing is read from disk at request time.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const css = readFileSync(new URL('src/style.css', root), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\s+/g, ' ')
    .replace(/\s*([{}:;,>])\s*/g, '$1')
    .replace(/;}/g, '}')
    .trim();
const config = JSON.parse(readFileSync(new URL('site-config.json', root), 'utf8'));

writeFileSync(
    new URL('src/assets.gen.mjs', root),
    '// Generated by scripts/build.mjs — do not edit.\n'
    + 'export const CSS = ' + JSON.stringify(css) + ';\n'
    + 'export const CONFIG = ' + JSON.stringify(config) + ';\n'
);
console.log(`assets.gen.mjs written (css ${css.length} bytes)`);
